local function as_list(value)
    if type(value) ~= 'table' then return {} end
    if value[1] ~= nil or next(value) == nil then return value end
    local out = {}
    for _, item in pairs(value) do out[#out + 1] = item end
    return out
end

-- Is this unit resource loaded? A nil answer means "do not look it up".
local function loaded(key, label)
    if not can_get or key == nil then return nil end
    trace('can_get unit ', label)
    local ok, yes = pcall(can_get, 'unit', key)
    if not ok then return nil end
    return yes == true
end

-- Resources known only by their 64-bit id (28 of the targets: the sample container,
-- mission carryables...) are asked about in whichever id form can_get understands on this game, found
-- by a self-test: the helldiver avatar's id must be "loaded" and a made-up id must not be. If no form
-- passes, those resources are not looked up at all (0.1.1-0.4.0 behaviour).
local AVATAR_HEX = '4d1c334d294dfa97'   -- murmur64 of AVATAR (checked by the tests)
local BOGUS_HEX = '0123456789abcdef'
local HEX_LOOKUPS = true    -- 0.9.0: mission items are mostly id-only; looked up once the self-test passes
local id_form            -- 'IdString64' | 'text' | false (none works) | nil (not tested yet)

local function id_key(hex, form)
    if form == 'IdString64' then
        if not (sr.IdString64 and type(sr.IdString64.from_hex) == 'function') then return nil end
        local ok, value = pcall(sr.IdString64.from_hex, hex)
        if ok then return value end
        return nil
    elseif form == 'text' then
        return '#ID[' .. hex .. ']'
    end
end

local function detect_id_form()
    if id_form ~= nil or not can_get then return end
    for _, form in ipairs({'IdString64', 'text'}) do
        local yes = loaded(id_key(AVATAR_HEX, form), 'avatar by id (' .. form .. ')')
        local no = loaded(id_key(BOGUS_HEX, form), 'made-up id (' .. form .. ')')
        log(string.format('id self-test %s: avatar=%s made-up=%s', form, tostring(yes), tostring(no)))
        if yes == true and no == false then
            id_form = form
            log('unnamed targets: id form ' .. form .. ' works' .. (HEX_LOOKUPS and ' - looked up by id' or ' (lookups off in this version)'))
            return
        end
    end
    id_form = false
    log('unnamed targets: no id form passed the self-test - they stay skipped')
end

local function units_of(world, key, label)
    trace('units_by_resource ', label)
    if chef_has('call_kind') then
        -- through Chef Shared Loader's guard: a call that ever ends the game is skipped from then on (per kind)
        local value, why = CHEF.call_kind('World.units_by_resource', label, world, key)
        if value == nil then return {}, why end
        return as_list(value)
    end
    local ok, value = pcall(sr.World.units_by_resource, world, key)
    if not ok then return {}, value end
    return as_list(value)
end

-- Position of a unit returned this very frame, as plain numbers (handles are never kept).
local function position_of(unit)
    if chef_has('unit_alive') and chef_has('unit_position') then
        -- Chef Shared Loader's own: it refuses units that can't be asked (one built at run time, one from a
        -- world that's gone) instead of ending the game
        if not CHEF.unit_alive(unit) then return nil end
        local x, y, z = CHEF.unit_position(unit)
        if type(x) ~= 'number' or type(y) ~= 'number' or type(z) ~= 'number' then return nil end
        for _, v in ipairs({x, y, z}) do
            if v ~= v or math.abs(v) > 1e7 then return nil end
        end
        return x, y, z
    end
    trace('alive')
    local alive_ok, alive = pcall(sr.Unit.alive, unit)
    if not alive_ok or alive ~= true then return nil end
    trace('world_position')
    local ok, p = pcall(sr.Unit.world_position, unit, 1)
    if not ok or p == nil then return nil end
    local x, y, z
    local read = pcall(function() x, y, z = sr.Vector3.x(p), sr.Vector3.y(p), sr.Vector3.z(p) end)
    if not read or type(x) ~= 'number' or type(y) ~= 'number' or type(z) ~= 'number' then return nil end
    for _, v in ipairs({x, y, z}) do
        if v ~= v or math.abs(v) > 1e7 then return nil end  -- NaN or absurd
    end
    return x, y, z
end

-- --------------------------------------------------------------- the sweep --
local keys = {}          -- { group, label, name or hex }
local found = {}         -- per key index: list of {x, y, z} from the last time it was read
local players = {}       -- list of {x, y, z}: every helldiver avatar (teammates and bodies too)
local me                 -- the one of them nearest the camera: you (or whoever the camera follows)
local cursor = 1
local stats = {sweeps = 0, looked_up = 0, skipped_unloaded = 0, units = 0, key_errors = 0, frames = 0, dots_peak = 0}

local function build_keys()
    local unnamed = 0
    for _, t in ipairs(TARGETS) do
        if t.name then
            keys[#keys + 1] = {group = t.group, name = t.name, label = t.name, icon = t.icon, worn = t.worn, near = t.near, taken = t.taken, height = t.height}
        elseif t.hex then
            unnamed = unnamed + 1
            keys[#keys + 1] = {group = t.group, hex = t.hex, label = t.hex, icon = t.icon, worn = t.worn, near = t.near, taken = t.taken, height = t.height}
        end
    end
    log(string.format('%d target resources: %d named, %d by id only (looked up if the id self-test passes)',
        #keys, #keys - unnamed, unnamed))
end

-- The key to ask can_get and units_by_resource with, or nil to skip this resource.
local function key_for(k)
    if k.name then return k.name, k.name end
    if not HEX_LOOKUPS or not id_form then return nil end
    -- units_by_resource takes an IdString64 (as the reference mods use it); can_get takes the tested form
    return id_key(k.hex, id_form), id_key(k.hex, 'IdString64')
end

-- Which resources had units in the last sweep: "label=count ..." for the status line.
local function found_summary()
    local parts = {}
    for i = 1, #keys do
        local n = found[i] and #found[i] or 0
        if n > 0 then
            local short = string.match(keys[i].label, '([^/]+)$') or keys[i].label
            parts[#parts + 1] = short .. '=' .. n
        end
    end
    return #parts > 0 and table.concat(parts, ' ') or 'none'
end

local players_read_at

-- (0.28-0.31 asked vehicles their animation state; that crashed the game soon after an exosuit was
-- destroyed, its state machine gone: no animation call is made any more.)

-- Since when a vehicle has stayed where it stopped. It is matched to the nearest of last frame's within
-- TRACK_STEP; it is still while it stays within STILL_EPS of its anchor (where it stopped). Read every
-- frame, a slow vehicle moves less than STILL_EPS from one frame to the next, so the last frame's
-- position is not the measure.
local function track(previous, x, y, z, now)
    local best, best_d = nil, TRACK_STEP * TRACK_STEP
    for _, q in ipairs(previous) do
        local dx, dy, dz = q[1] - x, q[2] - y, q[3] - z
        local d = dx * dx + dy * dy + dz * dz
        if d < best_d then best, best_d = q, d end
    end
    local armed = best ~= nil and best.armed or nil   -- it had weapons on it (kept while it is followed)
    if best ~= nil and best.anchor ~= nil then
        local a = best.anchor
        if math.abs(a[1] - x) < STILL_EPS and math.abs(a[2] - y) < STILL_EPS and math.abs(a[3] - z) < STILL_EPS then
            return {x, y, z, still_since = best.still_since, anchor = a, armed = armed, lost = best.lost}
        end
    end
    return {x, y, z, still_since = now, anchor = {x, y, z}, armed = armed, lost = best ~= nil and best.lost or nil}
end

local function read_players(world, now)
    local list = {}
    -- The avatar is in every world with a helldiver (the ship too); that is how 0.1.0's reference mod uses it.
    for _, unit in ipairs(units_of(world, AVATAR, 'avatar')) do
        local x, y, z = position_of(unit)
        if x then list[#list + 1] = {x, y, z, unit = unit} end
    end
    -- An empty read for a moment (a ragdoll, a respawn) must not blank every dot: keep the last positions briefly.
    if #list > 0 then
        players, players_read_at = list, now
    elseif players_read_at == nil or now - players_read_at > PLAYERS_HOLD_S then
        players = list
    end
end

-- Read one resource: where its units are now (plain numbers; handles are not kept).
local function read_key(world, i)
    local points = {}
    local ask, lookup = key_for(keys[i])
    if loaded(ask, keys[i].label) and lookup ~= nil then
        local units = units_of(world, lookup, keys[i].label)
        for _, unit in ipairs(units) do
            local x, y, z = position_of(unit)
            if x then points[#points + 1] = {x, y, z, unit = unit} end
        end
        return points, true
    end
    return points, false
end

-- Resources with an item near you in the last frame: read again every frame, so an item thrown by an
-- explosion moves smoothly instead of jumping about four times a second.
local hot = {}           -- list of key indices, made by collect_dots
local hot_reads = 0      -- for the status line

local function refresh_hot(world, first, last)
    local done = 0
    for _, i in ipairs(hot) do
        if done >= HOT_PER_FRAME then break end
        if i < first or i > last then  -- (the sweep has just read the ones in its own batch)
            found[i] = read_key(world, i)
            done = done + 1
        end
    end
    hot_reads = hot_reads + done
end

local function sweep_step(world)
    local first = cursor
    local last = math.min(cursor + KEYS_PER_FRAME - 1, #keys)
    for i = cursor, last do
        local points = {}
        local ask, lookup = key_for(keys[i])
        if loaded(ask, keys[i].label) and lookup ~= nil then
            stats.looked_up = stats.looked_up + 1
            local units, problem = units_of(world, lookup, keys[i].label)
            if problem ~= nil then
                stats.key_errors = stats.key_errors + 1
                if stats.key_errors <= 5 then log('lookup failed for ' .. keys[i].label .. ': ' .. tostring(problem)) end
            end
            for _, unit in ipairs(units) do
                local x, y, z = position_of(unit)
                if x then points[#points + 1] = {x, y, z, unit = unit} end
            end
            stats.units = stats.units + #points
        else
            stats.skipped_unloaded = stats.skipped_unloaded + 1
        end
        found[i] = points
    end
    refresh_hot(world, first, last)
    cursor = last + 1
    if cursor > #keys then
        cursor = 1
        stats.sweeps = stats.sweeps + 1
    end
end

-- -------------------------------------------------------------------- draw --
-- Diamonds are outlines of a square on its corner, like the game's own pickup icon. They are drawn on
-- the screen (the screen GUI section); only when that is not possible, with a line object in the 3D
-- scene, which an upscaler's performance mode clips to the top-left quarter. A line object is never
-- destroyed: its world may already be gone when we notice a change, and it goes away with its world.

-- Distance from you (the helldiver nearest the camera; without a camera, the nearest helldiver), the
-- helldiver it is measured from, and whether the unit is on any helldiver's body (worn or held). A body
-- is still a helldiver here (0.16): its empty sample container stays hidden, and what it dropped lands
-- beside it, within reach of the same rule.
local function measure(x, y, z, worn)
    local carried, mine, others, nearest, nearest_d = false, false, false, nil, nil
    for _, p in ipairs(players) do
        local dx, dy, dz = x - p[1], y - p[2], z - p[3]
        -- worn or held, at any height (prone too)
        local radius = worn or CARRIED_RADIUS   -- a target's own reach (the sample container swings wide)
        if dx * dx + dy * dy < radius * radius and dz > CARRIED_LOW and dz < CARRIED_HEIGHT then
            carried = true
        end
        local d = math.sqrt(dx * dx + dy * dy + dz * dz)
        -- in (or at) a vehicle: you, or someone else
        if d < VEHICLE_BUSY then
            if p == me then mine = true else others = true end
        end
        if nearest_d == nil or d < nearest_d then nearest, nearest_d = p, d end
    end
    local who = me or nearest
    if who == nil then return nil end
    local dx, dy, dz = x - who[1], y - who[2], z - who[3]
    return math.sqrt(dx * dx + dy * dy + dz * dz), who, carried, mine, others
end

-- Vehicles seen last frame, each tracked like a helldiver (track): since when it has stood still.
local vehicles_seen = {}

local function follow_vehicle(p, now, seen_now)
    local t = track(vehicles_seen, p[1], p[2], p[3], now)
    seen_now[#seen_now + 1] = t
    return t
end

-- Is any of these points within r of p?
local function near(list, p, r)
    for _, v in ipairs(list) do
        local dx, dy, dz = p[1] - v[1], p[2] - v[2], p[3] - v[3]
        if dx * dx + dy * dy + dz * dz < r * r then return true end
    end
    return false
end

local SHIP_HIDDEN = {mission = true, carry = true, dropoffs = true, controls = true}

-- Last frame's counts per group, for the status line: drawn, hidden as worn/held, out of range.
local last_counts = {}

-- Launch codes and keycards (targets with 'taken'): picked up, the unit stays where it lay, alive and
-- unchanged in everything the engine lets a mod read (2.1.0 test logs). So they are taken for picked up when
-- you press the interact key (TAKE_KEY) within TAKE_REACH of them, or a teammate has been within
-- TAKE_TEAMMATE_REACH of them for TAKE_HOLD_S (their keys can't be read; they pick codes up running past, so
-- briefly). You walking past leaves them marked. Without the loader's keyboard: you count as a teammate.
local TAKE_REACH = 2
local TAKE_TEAMMATE_REACH = 1.5
local TAKE_HOLD_S = 0.5
local TAKE_KEY = 'e'
-- Per-unit tables are keyed by the unit itself, weakly: under Chef Shared Loader every unit's tostring is the
-- same (one key for all would mix units up).
local function by_unit() return setmetatable({}, {__mode = 'k'}) end
local reached = by_unit()     -- per unit: since when a teammate has been at it
local taken = by_unit()       -- per unit: picked up (this world)

local function check_taken(p, now)
    local id = p.unit or string.format('%.0f %.0f %.0f', p[1], p[2], p[3])
    if taken[id] then return true end
    local keys_known = chef_has('key_down')
    local by, other = nil, false
    for _, h in ipairs(players) do
        local dx, dy, dz = p[1] - h[1], p[2] - h[2], p[3] - h[3]
        local d2 = dx * dx + dy * dy + dz * dz
        if h == me and keys_known then
            if d2 < TAKE_REACH * TAKE_REACH then
                local ok, down = pcall(CHEF.key_down, TAKE_KEY)
                if ok and down then by = 'you, with the interact key' end
            end
        elseif d2 < TAKE_TEAMMATE_REACH * TAKE_TEAMMATE_REACH then
            other = true
        end
    end
    if other then
        reached[id] = reached[id] or now
        if by == nil and now - reached[id] >= TAKE_HOLD_S then by = 'a helldiver standing at it' end
    else
        reached[id] = nil
    end
    if by then
        taken[id] = true
        log(string.format('taken: the item at %.1f %.1f %.1f is taken for picked up (%s)', p[1], p[2], p[3], by))
        return true
    end
    return false
end

local function collect_dots(now)
    local dots = {}
    local counts = {}
    local new_hot = {}
    local seen_now = {}
    local wrecks = {}        -- exosuit wrecks: the exosuit beside one is destroyed (its unit may stay)
    local arms = {}          -- vehicles' weapon units: a vehicle that had some and has none now is destroyed
    local dropoffs = {}      -- a mission item or load beside one is delivered (2.1.0)
    local racks = {}         -- artillery ready racks: a shell in one is loaded (2.1.0)
    for i = 1, #keys do
        local group = keys[i].group
        local list = (group == 'wrecks' and wrecks) or (group == 'arms' and arms) or (group == 'dropoffs' and dropoffs) or (group == 'loaders' and racks) or nil
        if list and found[i] then
            for _, p in ipairs(found[i]) do list[#list + 1] = p end
        end
    end
    -- on the ship: no mission markers (diamonds were seen under the hellpods after a mission, 2.0.1)
    local on_ship = chef_has('in_mission') and not CHEF.in_mission()
    for i = 1, #keys do
        local group = keys[i].group
        local range = SHOW[setting_of(group)] ~= false and (RANGE[setting_of(group)] or 0) or 0
        if on_ship and SHIP_HIDDEN[group] then range = 0 end
        local points = found[i]
        if points and range > 0 then
            local c = counts[group] or {drawn = 0, worn = 0, far = 0}
            counts[group] = c
            local near_any = false
            for _, p in ipairs(points) do
                local d, who, carried, mine, others = measure(p[1], p[2], p[3], keys[i].worn)
                if d ~= nil and d <= range + HOT_MARGIN then near_any = true end
                if d == nil or d > range then
                    c.far = c.far + 1
                elseif group == 'vehicles' then
                    -- destroyed, you in or at it, or someone else in a moving one: no marker
                    local v = follow_vehicle(p, now, seen_now)
                    local parked = now - v.still_since >= VEHICLE_PARKED_S
                    local armed_now = near(arms, p, ARMS_NEAR)
                    if armed_now then v.armed, v.lost = true, nil end
                    local destroyed = near(wrecks, p, WRECK_NEAR) or (v.armed and not armed_now)
                    if destroyed and not v.lost then
                        v.lost = true
                        log('vehicle: ' .. (string.match(keys[i].label, '([^/]+)$') or keys[i].label)
                            .. ' lost its weapons (or is by a wreck) - taken for destroyed')
                    end
                    if destroyed or mine or (others and not parked) then
                        c.worn = c.worn + 1
                    else
                        c.drawn = c.drawn + 1
                        dots[#dots + 1] = {p[1], p[2], p[3] + (keys[i].height or GROUP_HEIGHT.vehicles), d, who, group, keys[i].icon}
                    end
                elseif LOOK.hide_near and (keys[i].near or NEAR_ME[group]) and me ~= nil and who == me
                    and d < (keys[i].near or NEAR_ME[group]) - NEAR_OVERLAP then
                    c.worn = c.worn + 1
                elseif keys[i].taken and check_taken(p, now) then
                    c.worn = c.worn + 1
                elseif carried and group ~= 'dropoffs' and group ~= 'controls' then   -- never worn; a teammate may stand at it
                    c.worn = c.worn + 1
                elseif (group == 'mission' or group == 'carry') and near(dropoffs, p, DELIVERED_NEAR) then
                    c.worn = c.worn + 1
                elseif group == 'carry' and near(racks, p, LOADED_NEAR) then
                    c.worn = c.worn + 1
                else
                    c.drawn = c.drawn + 1
                    dots[#dots + 1] = {p[1], p[2], p[3] + (GROUP_HEIGHT[group] or DOT_HEIGHT), d, who, group, keys[i].icon}
                end
            end
            if near_any then new_hot[#new_hot + 1] = i end
        end
    end
    last_counts = counts
    hot = new_hot
    vehicles_seen = seen_now
    if #dots > MAX_DOTS then
        table.sort(dots, function(a, b) return a[4] < b[4] end)
        for i = #dots, MAX_DOTS + 1, -1 do dots[i] = nil end
    end
    return dots
end

-- The four corners of a diamond above a dot, facing its helldiver's eyes: top, right, bottom, left.
local function diamond(d)
    local cx, cy, cz = d[1], d[2], d[3]  -- z is up in this engine; d[3] is already above the unit
    local eye = d[5]
    local vx, vy, vz = cx - eye[1], cy - eye[2], cz - (eye[3] + EYE_HEIGHT)
    local len = math.sqrt(vx * vx + vy * vy + vz * vz)
    if len < 1e-3 then vx, vy, vz, len = 1, 0, 0, 1 end
    vx, vy, vz = vx / len, vy / len, vz / len
    local ux, uy = vy, -vx                              -- across the view, level: v x up(0,0,1)
    local ul = math.sqrt(ux * ux + uy * uy)
    if ul < 1e-3 then ux, uy, ul = 1, 0, 1 end          -- looking straight up or down
    ux, uy = ux / ul, uy / ul
    local wx, wy, wz = uy * vz, -ux * vz, ux * vy - uy * vx  -- across the view, upward: u x v
    local h = math.min(DIAMOND_MAX, math.max(DIAMOND_MIN, d[4] * DIAMOND_PER_M))
    local w = h * DIAMOND_ASPECT
    return {cx + h * wx, cy + h * wy, cz + h * wz},
           {cx + w * ux, cy + w * uy, cz},
           {cx - h * wx, cy - h * wy, cz - h * wz},
           {cx - w * ux, cy - w * uy, cz}
end

local function v3(p) return sr.Vector3(p[1], p[2], p[3]) end

-- The game's own field of view: vertical_fov in its settings file (55 by default on this PC), read
-- again every GAME_FOV_EVERY_S so a change in the game's options follows. 0.6.0-0.7.1 assumed 50 and
-- the diamonds drifted away from items toward the screen edges.
local game_fov = {value = nil, read_at = nil, path = nil}

local function read_game_fov(now)
    if game_fov.read_at ~= nil and now - game_fov.read_at < GAME_FOV_EVERY_S then return game_fov.value end
    game_fov.read_at = now
    if game_fov.path == nil then
        local ok, appdata = pcall(os.getenv, 'APPDATA')
        if not ok or type(appdata) ~= 'string' then return game_fov.value end
        game_fov.path = appdata .. '\\Arrowhead\\Helldivers2\\user_settings.config'
    end
    local okf, f = pcall(io.open, game_fov.path, 'rb')
    if not okf or f == nil then return game_fov.value end
    local okr, text = pcall(f.read, f, '*a')
    pcall(f.close, f)
    local value = okr and type(text) == 'string' and tonumber(string.match(text, 'vertical_fov%s*=%s*([%d%.]+)'))
    if value and value >= 20 and value <= 120 and value ~= game_fov.value then
        game_fov.value = value
        log('field of view: ' .. value .. ' degrees from the game settings')
    end
    return game_fov.value
end

current_fov = function()
    return read_game_fov(os.clock()) or VERTICAL_FOV
end

-- screen GUI ----------------------------------------------------------------
-- 0.5.0 showed that everything drawn in the 3D scene (lines, world GUI) is clipped to the top-left
-- quarter at a low render scale, while sitting at the right place. The HUD is not clipped: it is a
-- screen GUI, drawn after upscaling. So each item is projected to the screen here, with the camera
-- pose World.debug_camera_pose gives (it follows the game camera: 0.4.0 probe), and drawn as a small
-- diamond in a screen GUI on the UI world (the world that is not the main one, as DiverKit does).
-- The camera's field of view cannot be read (no camera object): it comes from the game's settings file.
local screen = {off = false}   -- handle, ui (its world), immediate, ids
local function forget_screen() screen.handle, screen.ui, screen.ids = nil, nil, nil end

-- Is this world still one of the game's worlds? (Compared with ==, as worlds are throughout.)
local function world_alive(w)
    if w == nil or type(sr.Application.worlds) ~= 'function' then return false end
    local ok, worlds = pcall(sr.Application.worlds)
    if not ok or type(worlds) ~= 'table' then return false end
    for _, x in ipairs(worlds[1] ~= nil and worlds or as_list(worlds)) do
        if same_world(x, w) then return true end
    end
    return false
end

-- Let go of the screen GUI: destroyed if its world is still there (it lives as long as the UI world,
-- across missions; 0.15 left one behind at every world change), else just forgotten.
local function release_screen()
    if screen.handle ~= nil and world_alive(screen.ui) then
        if not screen.immediate and screen.ids then
            for _, id in ipairs(screen.ids) do pcall(sr.Gui.destroy_triangle, screen.handle, id) end
        end
        if type(sr.World.destroy_gui) == 'function' then
            trace('destroy_gui')
            pcall(sr.World.destroy_gui, screen.ui, screen.handle)
        end
    end
    forget_screen()
end

local function xyz_of(v)
    local x, y, z
    local ok = pcall(function() x, y, z = sr.Vector3.x(v), sr.Vector3.y(v), sr.Vector3.z(v) end)
    if ok and type(x) == 'number' and type(y) == 'number' and type(z) == 'number' then return {x, y, z} end
end

-- The game's own camera, through Chef Shared Loader (2.1.0): where it is, where it looks, and its real field
-- of view (a scope or a speeding vehicle changes it; the settings file's does not). Level: no roll.
local function camera_from_chef()
    local ok, d = pcall(CHEF.camera)
    if not ok or type(d) ~= 'table' or type(d.x) ~= 'number' or type(d.fx) ~= 'number' then return nil end
    local fx, fy, fz = d.fx, d.fy, d.fz
    local level = math.sqrt(fx * fx + fy * fy)
    if level < 1e-6 then return nil end                 -- straight up or down
    local rx, ry = fy / level, -fx / level              -- right: forward x up
    local cam = {translation = {d.x, d.y, d.z}, forward = {fx, fy, fz}, right = {rx, ry, 0},
                 up = {ry * fz, -rx * fz, rx * fy - ry * fx}}   -- right x forward
    if type(d.fov) == 'number' and d.fov > 0 then
        cam.fov = d.fov < 3.2 and math.deg(d.fov) or d.fov   -- the engine gives radians
    end
    return cam
end

local function camera_of(world)
    if CHEF then
        local cam = camera_from_chef()
        if cam then
            if not screen.chef_camera_logged then
                screen.chef_camera_logged = true
                log("camera: the game's own (Chef Shared Loader), field of view " .. tostring(cam.fov))
            end
            return cam
        end
    end
    if not (type(sr.World.debug_camera_pose) == 'function' and sr.Matrix4x4) then return nil end
    local M4 = sr.Matrix4x4
    local ok, pose = pcall(sr.World.debug_camera_pose, world)
    if not ok or pose == nil then return nil end
    local cam = {}
    for _, part in ipairs({'translation', 'right', 'forward', 'up'}) do
        if type(M4[part]) ~= 'function' then return nil end
        local okp, v = pcall(M4[part], pose)
        cam[part] = okp and xyz_of(v) or nil
        if cam[part] == nil then return nil end
    end
    local t = cam.translation
    if t[1] == 0 and t[2] == 0 and t[3] == 0 then return nil end  -- not set yet (first frames of a world)
    return cam
end

-- The world to put the screen GUI on: another world than the main one if there is one (the UI world,
-- as DiverKit finds it), else the main world itself. Also returns a note on the worlds there are.
local function ui_world(main)
    if type(sr.Application.worlds) ~= 'function' then return main, 'Application.worlds missing' end
    local ok, worlds = pcall(sr.Application.worlds)
    if not ok or type(worlds) ~= 'table' then return main, 'Application.worlds failed' end
    local list = worlds[1] ~= nil and worlds or as_list(worlds)
    local count, others, other = 0, 0, nil
    for _, w in ipairs(list) do
        count = count + 1
        if not same_world(w, main) then
            others = others + 1
            if others == SCREEN_WORLD then other = w end
        end
    end
    return other or main, string.format('%d world(s), %d besides the main one, setting %d', count, others, SCREEN_WORLD)
end

-- Why the screen could not be drawn on, once per world (0.6.0 fell back silently).
local function screen_why(world_id, why)
    if screen.why_logged == world_id then return end
    screen.why_logged = world_id
    log('drawing: screen GUI not used here (' .. why .. ') - drawing in the 3D scene')
end

local function screen_gui(ui)
    if screen.handle ~= nil and same_world(screen.ui, ui) then return screen.handle end
    release_screen()   -- another UI world: the old GUI goes with it, or is destroyed if its world stayed
    if type(sr.World.create_screen_gui) ~= 'function' then
        screen.off = true
        log('drawing: no screen GUI in this game build')
        return nil
    end
    local errors = {}
    for _, flags in ipairs({{'immediate'}, {'scale', 1, 1}}) do
        trace('create_screen_gui ', flags[1])
        local ok, made = pcall(sr.World.create_screen_gui, ui, unpack(flags))
        if ok and made ~= nil then
            screen.handle, screen.ui, screen.immediate, screen.ids = made, ui, flags[1] == 'immediate', {}
            log('drawing: ' .. (screen.immediate and 'immediate' or 'retained') .. ' screen GUI'
                .. ', vertical field of view ' .. current_fov() .. ' degrees')
            return made
        end
        errors[#errors + 1] = flags[1] .. ': ' .. tostring(made)
    end
    screen.off = true
    log('drawing: create_screen_gui failed (' .. table.concat(errors, '; ') .. ')')
    return nil
end

local function dot3(a, b) return a[1] * b[1] + a[2] * b[2] + a[3] * b[3] end

-- How big a marker is drawn: full size up to FULL_SIZE_M away, LOOK.smallest at the edge of its kind's range.
local FULL_SIZE_M = 10
local SMALLEST = 0.7          -- the smallest of the game icons' pixel sizes (ICON_PIXELS); smaller: scaled from it
local FADE_LEAST = 0.2
local POINTER = {gap = 3, half = 9, slope = 0.5, line = 2}   -- the wide V under a vehicle's icon, pixels at full size
-- 0 up to FULL_SIZE_M away, 1 at the edge of its kind's range
local function far_share(d)
    local range = RANGE[setting_of(d[6])] or 0
    if range <= FULL_SIZE_M then return 0 end
    return math.max(0, math.min(1, (d[4] - FULL_SIZE_M) / (range - FULL_SIZE_M)))
end
local function size_of(d) return 1 - (1 - LOOK.smallest) * far_share(d) end
local function opacity_of(d)
    if not LOOK.fade or d[6] ~= 'supplies' then return LOOK.opacity end   -- mission markers stay easy to find
    return LOOK.opacity * (1 - (1 - FADE_LEAST) * far_share(d))
end

-- Screen position (pixels, origin bottom-left, y up) of a dot, or nil if it is behind or off screen.
local function project(cam, d, width, height, f)
    local p = {d[1] - cam.translation[1], d[2] - cam.translation[2], d[3] - cam.translation[3]}
    local depth = dot3(p, cam.forward)
    if depth < 0.5 then return nil end
    local sx = width / 2 + dot3(p, cam.right) / depth * f
    local sy = height / 2 + dot3(p, cam.up) / depth * f
    if sx < -SCREEN_DIAMOND or sx > width + SCREEN_DIAMOND or sy < -SCREEN_DIAMOND or sy > height + SCREEN_DIAMOND then
        return nil
    end
    -- whole pixels: between them the thin outline smears differently each frame and seems to waver
    return math.floor(sx + 0.5), math.floor(sy + 0.5)
end

-- Returns true when the screen GUI handled this frame, false to draw in the 3D scene instead.
local function screen_draw(world, world_id, dots)
    if screen.off then return false end
    if #dots == 0 and (screen.immediate or not screen.ids or #screen.ids == 0) then return true end
    local cam = camera_of(world)
    if cam == nil then
        screen.cam_misses = (screen.cam_misses or 0) + 1
        if screen.cam_misses > 600 then screen_why(world_id, 'no camera pose for 600 frames') end
        return false
    end
    screen.cam_misses = 0
    local ui, worlds_note = ui_world(world)
    if screen.worlds_logged ~= world_id then
        screen.worlds_logged = world_id
        log('drawing: ' .. worlds_note .. '; screen GUI goes on '
            .. (same_world(ui, world) and 'the main world' or ('other world #' .. SCREEN_WORLD)))
    end
    if not (sr.Gui and type(sr.Gui.resolution) == 'function' and type(sr.Gui.triangle) == 'function') then
        screen.off = true
        log('drawing: Gui.resolution or Gui.triangle missing')
        return false
    end
    local okr, width, height = pcall(sr.Gui.resolution)
    if not okr or type(width) ~= 'number' or type(height) ~= 'number' or width < 1 or height < 1 then
        screen_why(world_id, 'Gui.resolution gave ' .. tostring(width) .. ' ' .. tostring(height))
        return false
    end
    local g = screen_gui(ui)
    if g == nil then return false end
    local ok, problem = pcall(function()
        trace('screen triangles dots=', #dots)
        if not screen.immediate then
            for _, id in ipairs(screen.ids) do pcall(sr.Gui.destroy_triangle, g, id) end
            screen.ids = {}
        end
        local inks = {}             -- by tint, then alpha (0..255)
        local tint = nil            -- this marker's colour: nil white, else {r, g, b}
        local function ink_of(alpha)
            alpha = math.floor(alpha)
            local by = inks[tint or 'white']
            if by == nil then
                by = {}
                inks[tint or 'white'] = by
            end
            local c = by[alpha]
            if c == nil then
                c = tint and sr.Color(alpha, tint[1], tint[2], tint[3]) or sr.Color(alpha, 255, 255, 255)  -- ARGB
                by[alpha] = c
            end
            return c
        end
        local ink = ink_of(255)     -- this marker's: its opacity (LOOK)
        local opacity = 1
        local function tri(a, b, c)
            local id = sr.Gui.triangle(g, a, b, c, SCREEN_LAYER, ink)
            if not screen.immediate and id ~= nil then screen.ids[#screen.ids + 1] = id end
        end
        -- an icon: each polygon as a fan of triangles
        local function pixels(list, sx, sy, k)   -- k: scale (below the smallest pixel size), else 1
            for _, r in ipairs(list) do
                local shade = ink_of(255 * r[5] / 4 * opacity)
                local x0, y0, x1, y1 = sx + r[1] * k, sy + r[2] * k, sx + r[3] * k, sy + r[4] * k
                local a, b = sr.Vector3(x0, 0, y0), sr.Vector3(x1, 0, y0)
                local c, d = sr.Vector3(x1, 0, y1), sr.Vector3(x0, 0, y1)
                local id1 = sr.Gui.triangle(g, a, b, c, SCREEN_LAYER, shade)
                local id2 = sr.Gui.triangle(g, a, c, d, SCREEN_LAYER, shade)
                if not screen.immediate then
                    if id1 ~= nil then screen.ids[#screen.ids + 1] = id1 end
                    if id2 ~= nil then screen.ids[#screen.ids + 1] = id2 end
                end
            end
        end
        -- under a vehicle's icon, a wide V pointing down at it (like the 0.11-0.25 vehicle marker's lower V)
        local thick = POINTER.line * math.sqrt(1 + POINTER.slope * POINTER.slope)   -- vertical, for the line at right angles
        local function pointer(list, sx, sy, size)
            local bottom = list.bottom
            if bottom == nil then   -- the icon's lowest pixel at this size, worked out once
                bottom = math.huge
                for _, r in ipairs(list) do bottom = math.min(bottom, r[2]) end
                list.bottom = bottom
            end
            local w, t = POINTER.half * size, thick * size
            local top = sy + bottom - POINTER.gap * size
            local l, a, r = {sx - w, top}, {sx, top - w * POINTER.slope}, {sx + w, top}
            for _, side in ipairs({{l, a}, {a, r}}) do
                local p1, p2 = side[1], side[2]
                tri(sr.Vector3(p1[1], 0, p1[2]), sr.Vector3(p2[1], 0, p2[2]), sr.Vector3(p2[1], 0, p2[2] + t))
                tri(sr.Vector3(p1[1], 0, p1[2]), sr.Vector3(p2[1], 0, p2[2] + t), sr.Vector3(p1[1], 0, p1[2] + t))
            end
        end
        local function icon(shape, sx, sy, size)
            local color = ink
            local k = shape.scale * size
            for _, poly in ipairs(shape.polys) do
                local first = sr.Vector3(sx + poly[1][1] * k, 0, sy + poly[1][2] * k)
                for n = 2, #poly - 1 do
                    local id = sr.Gui.triangle(g, first, sr.Vector3(sx + poly[n][1] * k, 0, sy + poly[n][2] * k),
                        sr.Vector3(sx + poly[n + 1][1] * k, 0, sy + poly[n + 1][2] * k), SCREEN_LAYER, color)
                    if not screen.immediate and id ~= nil then screen.ids[#screen.ids + 1] = id end
                end
            end
        end
        -- an outline: the band between an outer and an inner diamond, one quad (two triangles) per side;
        -- the lower half filled
        local f = (height / 2) / math.tan(math.rad(cam.fov or current_fov()) / 2)   -- once a frame
        -- the distance above a marker, in the game's font (Chef Shared Loader draws it, on its own screen size)
        local cw, ch
        if LOOK.distance and chef_has('text') and chef_has('screen') and chef_has('color') and chef_has('text_width') then
            local oks, w, h = pcall(CHEF.screen)
            if oks and type(w) == 'number' and type(h) == 'number' and w > 0 and h > 0 then cw, ch = w, h end
        end
        local function distance_above(sx, top, d)
            if cw == nil or d[6] ~= 'vehicles' then return end
            pcall(function()
                local px = math.max(1, ch / 1080 * DISTANCE_PX)
                local text = string.format('%dm', math.floor(d[4] + 0.5))
                local c = tint or {255, 255, 255}
                local color = CHEF.color(c[1], c[2], c[3], math.floor(255 * opacity))
                local x = sx * cw / width - CHEF.text_width(text, px) / 2
                -- bold: the loader's text has one weight, too thin at this size, so it goes down
                -- four times, a pixel apart
                local y = (top + 3) * ch / height
                for _, o in ipairs(BOLD) do CHEF.text(x + o[1], y + o[2], text, px, color) end
            end)
        end
        -- an icon from the game's texture, as tall as its pixel icon at this size; false when it can't be drawn
        local function texture_icon(name, full, sx, sy, size)
            local t = ICON_TEXTURES[name]
            if t == nil or cw == nil and not chef_has('screen') or not chef_has('bitmap') then return false end
            if full.span == nil then
                local lo, hi = math.huge, -math.huge
                for _, r in ipairs(full) do lo, hi = math.min(lo, r[2]), math.max(hi, r[4]) end
                full.span = hi - lo
            end
            local okd, drawn = pcall(function()
                local w, h = cw, ch
                if w == nil then w, h = CHEF.screen() end
                local k = full.span * size / (t[7] - t[5])          -- texture pixels to screen pixels
                local cx, cy = (t[4] + t[6]) / 2, (t[5] + t[7]) / 2  -- the icon's centre in the texture
                local x0, y1 = sx - cx * k, sy + cy * k              -- the texture's left and top edge
                local c = CHEF.color(255, 255, 255, math.floor(255 * opacity))
                return CHEF.bitmap(t[1], x0 * w / width, (y1 - t[3] * k) * h / height,
                    t[2] * k * w / width, t[3] * k * h / height, c)
            end)
            if okd and drawn then return true end
            if not screen.texture_note then
                screen.texture_note = true
                log('icons: a game texture could not be drawn (' .. tostring(drawn) .. ') - pixel icons instead')
            end
            return false
        end
        local function top_of(list, k)   -- the highest pixel of an icon, at this scale
            if list.top == nil then
                local top = -math.huge
                for _, r in ipairs(list) do top = math.max(top, r[4]) end
                list.top = top
            end
            return list.top * k
        end
        local CORNERS = {{0, 1}, {1, 0}, {0, -1}, {-1, 0}}        -- top, right, bottom, left
        for _, d in ipairs(dots) do
            local sx, sy = project(cam, d, width, height, f)
            local size = sx and size_of(d)
            if sx then
                opacity = opacity_of(d)
                tint = d[6] == 'vehicles' and VEHICLE_RGB or nil
                ink = ink_of(255 * opacity)
                if d[6] == 'samples' or d[6] == 'supplies' then sx, sy = sx + ICON_OFFSET[1], sy + ICON_OFFSET[2] end
            end
            if sx and d[7] and ICON_PIXELS[d[7]] then
                local sizes = ICON_PIXELS[d[7]]   -- full size first, then a pixel smaller each
                local step = math.floor((1 - size) / (1 - SMALLEST) * (#sizes - 1) + 0.5) + 1
                local list = sizes[math.max(1, math.min(#sizes, step))]
                local k = size < SMALLEST and size / SMALLEST or 1
                if not texture_icon(d[7], sizes[1], sx, sy, size) then
                    pixels(list, sx, sy, k)
                end
                if d[6] == 'vehicles' then pointer(list, sx, sy, size) end
                distance_above(sx, sy + top_of(list, k), d)
            elseif sx and d[7] and ICON_SHAPES[d[7]] then
                local shape = ICON_SHAPES[d[7]]
                icon(shape, sx, sy, size)
                if shape.top == nil then
                    shape.top = -math.huge
                    for _, poly in ipairs(shape.polys) do
                        for _, v in ipairs(poly) do shape.top = math.max(shape.top, v[2]) end
                    end
                end
                distance_above(sx, sy + shape.top * shape.scale * size, d)
            elseif sx then
                local outer = SCREEN_DIAMOND * size
                local inner = math.max(0, outer - math.max(1.5, SCREEN_LINE * size) * math.sqrt(2))  -- the band
                -- at right angles; a small one is filled
                -- screen GUI points are Vector3(x, 0, y)
                local o, i = {}, {}
                for k, c in ipairs(CORNERS) do
                    o[k] = sr.Vector3(sx + c[1] * outer, 0, sy + c[2] * outer)
                    i[k] = sr.Vector3(sx + c[1] * inner, 0, sy + c[2] * inner)
                end
                for k = 1, 4 do
                    local n = k % 4 + 1
                    tri(o[k], o[n], i[n])
                    tri(o[k], i[n], i[k])
                end
                tri(o[2], o[3], o[4])   -- right, bottom, left: the lower half
                distance_above(sx, sy + outer, d)
            end
        end
    end)
    if not ok then
        -- a passing failure (a GUI gone with its world, say) is tried again; only a lasting one turns it off
        screen.failures = (screen.failures or 0) + 1
        if screen.failures <= 3 then log('drawing: screen GUI failed (' .. tostring(problem) .. ')') end
        release_screen()
        if screen.failures >= SCREEN_FAILURES then
            screen.off = true
            log('drawing: screen GUI failed ' .. SCREEN_FAILURES .. ' times in a row - back to drawing in the 3D scene')
            return false
        end
        return true   -- this frame skipped; the next makes a new screen GUI
    end
    screen.failures = 0
    return true
end

-- line fallback -----------------------------------------------------------
local line, line_world_id, line_shown

local function forget_line()
    line, line_world_id, line_shown = nil, nil, false
end

local function line_for(world, world_id)
    if line ~= nil and line_world_id == world_id then return line end
    trace('create_line_object')
    local ok, created = pcall(sr.World.create_line_object, world, true)  -- true: drawn over walls
    if not ok or created == nil then return nil end
    line, line_world_id, line_shown = created, world_id, false
    return line
end

local function lines_draw(world, world_id, dots)
    if #dots == 0 and not line_shown then return end  -- nothing drawn and nothing to clear
    local lo = line_for(world, world_id)
    if lo == nil then return end
    local ok, problem = pcall(function()
        trace('line reset/add/dispatch dots=', #dots)
        sr.LineObject.reset(lo)
        if #dots == 0 then
            -- clear with an invisible line rather than dispatching an empty object
            local z = sr.Vector3(0, 0, 0)
            sr.LineObject.add_line(lo, sr.Color(0, 0, 0, 0), z, z)
        else
            local white = sr.Color(255, 255, 255, 255)  -- ARGB
            for _, d in ipairs(dots) do
                local corners = {diamond(d)}
                for k = 1, 4 do
                    sr.LineObject.add_line(lo, white, v3(corners[k]), v3(corners[k % 4 + 1]))
                end
            end
        end
        sr.LineObject.dispatch(world, lo)
    end)
    if ok then
        line_shown = #dots > 0
    else
        M.draw_errors = (M.draw_errors or 0) + 1
        if M.draw_errors <= 5 then log('draw failed: ' .. tostring(problem)) end
    end
end

local function shown()
    return line_shown or (screen.ids ~= nil and #screen.ids > 0)
end

local function forget_drawing()
    forget_screen()
    forget_line()
end

-- A new main world: the line object went with the old one; the screen GUI stays (on the UI world), only
-- what it shows is cleared.
local function new_main_world()
    forget_line()
    if screen.handle ~= nil and not screen.immediate and screen.ids then
        for _, id in ipairs(screen.ids) do pcall(sr.Gui.destroy_triangle, screen.handle, id) end
        screen.ids = {}
    end
end

local menus_released = 0

local function draw(world, world_id, now)
    local dots = collect_dots(now)
    if menu_open() then
        -- a menu is open: take the screen GUI away altogether, not just empty. Quitting goes through a
        -- menu, and a screen GUI still there when the game shuts down crashed its renderer on quitting
        -- (2.0.0 and before); removed here, frames before the quit, the engine finishes with it in time.
        if screen.handle ~= nil then
            release_screen()
            menus_released = menus_released + 1
            if menus_released <= 3 then log('menus: screen GUI removed while the menu is open') end
        end
        if line_shown then lines_draw(world, world_id, {}) end
        return
    end
    if screen_draw(world, world_id, dots) then
        -- drawn on the screen: clear anything the 3D scene still shows from before
        if line_shown then lines_draw(world, world_id, {}) end
    else
        lines_draw(world, world_id, dots)
    end
    if #dots > stats.dots_peak then stats.dots_peak = #dots end
end

-- A menu is open (Esc, the map...) while the mouse cursor shows. The markers are drawn on a screen GUI
-- that the game's menus do not cover at any layer (0.11-0.16), so they are hidden instead. Asked of
-- Window.show_cursor, if the engine has it; each change is logged (the first 20) to see that it works.
local cursor_shown = {last = nil, changes = 0, off = false}

menu_open = function()
    if cursor_shown.off then return false end
    local fn = sr.Window and sr.Window.show_cursor
    if type(fn) ~= 'function' then
        cursor_shown.off = true
        log('menus: no Window.show_cursor - markers stay over menus')
        return false
    end
    local ok, value = pcall(fn)
    if not ok then
        cursor_shown.off = true
        log('menus: Window.show_cursor failed (' .. tostring(value) .. ') - markers stay over menus')
        return false
    end
    local open = value == true
    if open ~= cursor_shown.last then
        cursor_shown.last = open
        cursor_shown.changes = cursor_shown.changes + 1
        if cursor_shown.changes <= 20 then log('menus: cursor ' .. (open and 'shown - markers hidden' or 'hidden')
            .. ' (Window.show_cursor gave ' .. tostring(value) .. ')') end
    end
    return open
end

-- You: the helldiver nearest the camera (third or first person alike); nil without a camera pose.
-- You: the helldiver nearest the camera. 2.1.0: and the same one from frame to frame, by its unit, unless
-- another is clearly nearer (under ME_SWITCH of your distance): a teammate passing the camera no longer
-- takes your place for a moment; after a respawn the camera is on the new one, far from the body.
local ME_SWITCH = 0.5
local me_unit
local me_changes = 0

local function pick_me(world)
    if #players == 0 then return nil end
    if #players == 1 then
        me_unit = players[1].unit
        return players[1]
    end
    local cam = camera_of(world)
    if cam == nil then return nil end
    local best, who, mine, mine_d
    for _, p in ipairs(players) do
        local dx, dy, dz = p[1] - cam.translation[1], p[2] - cam.translation[2], p[3] - cam.translation[3]
        local d = math.sqrt(dx * dx + dy * dy + dz * dz)
        if best == nil or d < best then best, who = d, p end
        if me_unit ~= nil and p.unit == me_unit then mine, mine_d = p, d end
    end
    if mine ~= nil and (who == mine or best >= ME_SWITCH * mine_d) then return mine end
    local id = who.unit
    if id ~= me_unit then
        me_unit = id
        me_changes = me_changes + 1
        if me_changes <= 50 then
            log(string.format('you: the helldiver at %.1f %.1f %.1f (%d helldivers)', who[1], who[2], who[3], #players))
        end
    end
    return who
end

-- -------------------------------------------------------------------- tick --
local started_at, next_status, last_world, world_seen_at
local world_seq, world_id = 0, nil

local function main_world()
    local ok, world = pcall(sr.Application.main_world)
    if ok then return world end
end

local function tick()
    local now = os.clock()
    if now - started_at < STARTUP_GRACE_S then return end
    local world = main_world()
    if world == nil then
        if last_world ~= nil then last_world, cursor, found, players, me, hot = nil, 1, {}, {}, nil, {} end
        new_main_world()
        return
    end
    if not same_world(world, last_world) then
        -- a new mission or the ship: forget everything read in the old world
        world_seq = world_seq + 1
        world_id = 'world #' .. world_seq
        last_world, world_seen_at, cursor, found, players, players_read_at, me = world, now, 1, {}, {}, nil, nil
        vehicles_seen = {}
        reached, taken, me_unit = by_unit(), by_unit(), nil
        hot = {}
        new_main_world()
        traced = 0
        write_line(tracefile, '--- world changed: ' .. world_id)
        log('world changed: ' .. world_id)
    end
    if now - world_seen_at < WORLD_SETTLE_S then return end
    stats.frames = stats.frames + 1
    local saved = temp_begin()
    local ok, problem = pcall(function()
        read_players(world, now)   -- every frame: a running helldiver's own items stay hidden
        me = pick_me(world)
        if #players > 0 and can_get then
            detect_id_form()
            sweep_step(world)
        end
        -- draw every frame; with no helldiver this clears whatever was drawn last
        if #players > 0 or shown() then draw(world, world_id, now) end
    end)
    temp_end(saved)
    if not ok then
        M.tick_errors = (M.tick_errors or 0) + 1
        if M.tick_errors <= 5 then log('tick failed: ' .. tostring(problem)) end
    end
    if now >= (next_status or 0) then
        next_status = now + STATUS_EVERY_S
        log(string.format('status: players=%d sweeps=%d looked_up=%d skipped_unloaded=%d units=%d '
            .. 'dots_peak=%d lookup_errors=%d near_resources=%d hot_reads=%d', #players, stats.sweeps, stats.looked_up,
            stats.skipped_unloaded, stats.units, stats.dots_peak, stats.key_errors, #hot, hot_reads))
        hot_reads = 0
        if #players > 0 then
            log('found: ' .. found_summary())
            local parts = {}
            for _, group in ipairs({'samples', 'supplies', 'mission', 'carry', 'dropoffs', 'controls', 'vehicles'}) do
                local c = last_counts[group]
                if c then parts[#parts + 1] = string.format('%s drawn=%d worn=%d far=%d', group, c.drawn, c.worn, c.far) end
            end
            log('last frame: ' .. (#parts > 0 and table.concat(parts, ' | ') or 'nothing found'))
        end
        stats.dots_peak = 0
    end
end

