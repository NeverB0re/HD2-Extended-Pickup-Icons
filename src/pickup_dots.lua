local function rect(x0, y0, x1, y1) return {{x0, y0}, {x1, y0}, {x1, y1}, {x0, y1}} end
-- the part of a circle (radius r, at the origin) beyond the line x = cut: side 1 right of it, -1 left
local function circle_cut(r, cut, side, n)
    local a0 = math.acos(cut / r)
    local from, to = -a0, a0
    if side < 0 then from, to = a0, 2 * math.pi - a0 end
    local pts = {}
    for k = 0, n do
        local a = from + (to - from) * k / n
        pts[#pts + 1] = {r * math.cos(a), r * math.sin(a)}
    end
    return pts
end
